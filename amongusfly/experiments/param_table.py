"""
Write docs/PARAMETERS.md: every fixed constant and every trainable adapter parameter (range,
starting value, trained values), read from the code that uses them.

    python -m amongusfly.experiments.param_table --runs explore_v5 seeker_v6 hider_v5
"""
from __future__ import annotations

import argparse
import json

import yaml

from amongusfly.agents import route_policy as rp
from amongusfly.motors import body_kinematic as bk
from amongusfly.paths import DOCS_DIR, REPO_ROOT, RESULTS_DIR
from amongusfly.train import adapter, explore_env
from amongusfly.world import pathing, skeld

FIXED = [
    # (group, name, value, unit, what it does)
    ("Body", "forward speed", "2.0", "units/s", "game speed of both roles; training uses the same speed"),
    ("Body", "body radius", "0.25", "units", "kinematic unicycle with wall sliding"),
    ("Body", "CAREFUL_CLEARANCE", bk.CAREFUL_CLEARANCE, "units", "below this clearance the fly slows down"),
    ("Body", "CAREFUL_MIN_FACTOR", bk.CAREFUL_MIN_FACTOR, "×speed", "slowest speed factor, at the wall"),
    ("Planner", "BODY_CLEARANCE", pathing.BODY_CLEARANCE, "units", "planned paths keep this far from walls"),
    ("Planner", "REPLAN_AFTER_BLOCKED_S", rp.REPLAN_AFTER_BLOCKED_S, "s", "wall contact before the route is re-planned"),
    ("Planner", "PROGRESS_UNITS", rp.PROGRESS_UNITS, "units", "getting this much closer counts as progress (commitment)"),
    ("Planner", "WALL_REPEL_GAIN", rp.WALL_REPEL_GAIN, "", "how hard the goal is bent away from a wall"),
    ("Planner", "WALL_REPEL_RANGE", rp.WALL_REPEL_RANGE, "units", "clearance at which the bend fades out"),
    ("Planner", "GOAL_SMOOTH_S", rp.GOAL_SMOOTH_S, "s", "time constant of the goal-direction low-pass filter"),
    ("Planner", "AVOID_FREE_UNITS", rp.AVOID_FREE_UNITS, "units", "probe fan (off; centring replaces it)"),
    ("Map", "MIN_VENT_CLEARANCE", skeld.MIN_VENT_CLEARANCE, "units", "vents snap to the nearest cell this far from walls"),
    ("Training", "SPIN_PENALTY", explore_env.SPIN_PENALTY, "points/s", "walker fitness lost per second spinning on the spot"),
    ("Training", "SPIN_WINDOW", f"{explore_env.SPIN_WINDOW * 20} ms", "", "window for the spin test (≥ 1 turn, < 1 unit progress)"),
]


def fmt(v) -> str:
    return f"{v:g}" if isinstance(v, (int, float)) else str(v)


def trained(run: str) -> dict:
    f = RESULTS_DIR / "train" / run / "best.json"
    return json.loads(f.read_text())["values"] if f.exists() else {}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", nargs=3, default=["explore_v5", "seeker_v6", "hider_v5"],
                    metavar=("WALKER", "SEEKER", "HIDER"))
    a = ap.parse_args()
    motors = yaml.safe_load((REPO_ROOT / "config" / "motors.yaml").read_text(encoding="utf-8"))
    cx = yaml.safe_load((REPO_ROOT / "config" / "cx.yaml").read_text(encoding="utf-8"))
    brain = yaml.safe_load((REPO_ROOT / "config" / "brain.yaml").read_text(encoding="utf-8"))
    lines = [
        "# Engineered parameters",
        "",
        "*Generated by `python -m amongusfly.experiments.param_table` from the code that uses these values. "
        "No connectome weight appears here: none is ever changed.*",
        "",
        "## Fixed (never trained)",
        "",
        "| Part | Parameter | Value | Unit | Role |",
        "|---|---|---|---|---|",
    ]
    lines += [f"| {g} | `{n}` | {fmt(v)} | {u} | {w} |" for g, n, v, u, w in FIXED]
    lines += [
        f"| Readout | `turn.deadband_hz` | {fmt(motors['turn']['deadband_hz'])} | Hz | left−right rate differences below this are ignored |",
        f"| Readout | `dash.threshold_hz` | {fmt(motors['dash']['threshold_hz'])} | Hz | mean DNp01 rate that triggers the escape dash |",
        f"| Readout | `goal_behind.source` | {motors['goal_behind']['source']} | | the goal-behind turn reads this cell type's rate directly |",
        f"| Brain | `connectome_weight_scale` | {fmt(brain['connectome_weight_scale'])} | | every connectome weight is multiplied by this |",
        f"| Compass | `r_max_hz` | {fmt(cx['r_max_hz'])} | Hz | peak rate of the EPG heading and FC2 goal bumps |",
        f"| Compass | `kappa` | {fmt(cx['kappa'])} | | bump concentration (von Mises) |",
        f"| Compass | `heading_sign` | {fmt(cx['heading_sign'])} | | world heading to preferred-angle frame |",
        f"| Compass | `goal_offset_deg` | {fmt(cx['goal_offset_deg'])} | deg | offset of the goal bump, set so turns have the right sign and PFL2 peaks with the goal behind |",
        f"| Compass | `pb_phase_convention` | {cx['pb_phase_convention']} | | left/right bridge numbering |",
        "",
        "## Trainable adapter (CMA-ES over a normalised vector; log scale where marked)",
        "",
        f"Trained values are the `best.json` of runs `{a.runs[0]}` (walker), `{a.runs[1]}` (seeker) and `{a.runs[2]}` (hider). "
        "A dash means the role does not use that parameter.",
        "",
        "| Parameter | Used by | Range | Start | Walker | Seeker | Hider |",
        "|---|---|---|---|---|---|---|",
    ]
    sets = {"walker": adapter.ROUTE_PARAMS, "seeker": adapter.SEEKER_PARAMS, "hider": adapter.HIDER_PARAMS}
    vals = dict(zip(sets, (trained(r) for r in a.runs)))
    seen: dict[str, adapter.Param] = {}
    users: dict[str, list[str]] = {}
    for role, ps in sets.items():
        for p in ps:
            seen.setdefault(p.name, p)
            users.setdefault(p.name, []).append(role)
    for name, p in seen.items():
        cells = [fmt(round(vals[r][name], 3)) if r in users[name] and name in vals[r] else "-" for r in sets]
        rng = f"{fmt(p.lo)}–{fmt(p.hi)}{' (log)' if p.log else ''}"
        lines.append(f"| `{name}` | {', '.join(users[name])} | {rng} | {fmt(p.init)} | " + " | ".join(cells) + " |")
    out = DOCS_DIR / "PARAMETERS.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out} ({len(FIXED) + 1} fixed, {len(seen)} trainable)")


if __name__ == "__main__":
    main()
